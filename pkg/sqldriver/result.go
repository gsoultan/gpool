package sqldriver

import (
	"database/sql/driver"

	"github.com/gsoultan/gpool/pkg/gpool"
)

// pgResult is the outcome of an Exec, implementing gpool.Result.
// It is an immutable value, so it carries no release hazard of its own.
type pgResult struct {
	result driver.Result
}

var _ gpool.Result = pgResult{}

// RowsAffected returns the number of rows the statement changed, or zero when the
// driver declines to say.
func (r pgResult) RowsAffected() int64 {
	if r.result == nil {
		return 0
	}

	affected, err := r.result.RowsAffected()
	if err != nil {
		return 0
	}
	return affected
}

// LastInsertID returns the identifier generated by the statement, and whether the
// driver supplied one. PostgreSQL has no equivalent, which is why this is here
// rather than on gpool.Result.
func (r pgResult) LastInsertID() (int64, bool) {
	if r.result == nil {
		return 0, false
	}

	id, err := r.result.LastInsertId()
	if err != nil {
		return 0, false
	}
	return id, true
}

// Release is a no-op, kept so callers can treat every result uniformly.
func (r pgResult) Release() {}
